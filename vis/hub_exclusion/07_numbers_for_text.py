#!/usr/bin/env python
"""numbers_for_text.md - every number quoted for the hub-exclusion result,
read from figures/hub_exclusion/data/. Descriptive; no tests beyond those
behind the figures. Each number is labelled as pooled over conditions or
specific to one condition. Regulator sets are the primary comparison; target
sets are reported in a separate section (supplementary figures only).
"""

import numpy as np
import pandas as pd

import hxcommon  # noqa: F401  (sets sys.path, CH2_VARIANT)
from hxcommon import (CONDS, CONSERVATIVE, HUB_CUTOFF, OUT, PAIR_CLASSES, PCT,
                      VKEYS, read)


def md(df, floatfmt="{:.3f}"):
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        cells = [floatfmt.format(v) if isinstance(v, (float, np.floating)) and np.isfinite(v)
                 else ("–" if isinstance(v, (float, np.floating)) else str(v)) for v in r]
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def pct(v):
    return f"{PCT[v]} %"


def kn(k, n):
    return f"{k}/{n} ({100 * k / n:.1f} %)" if n else f"{k}/{n}"


def class_table(e, col="median", n="n_pairs", p=None):
    """condition x threshold rows, pair-class columns: 'median (n=..)[, p]'."""
    def cell(r):
        s = f"{r[col]:.3f} (n={r[n]})" if np.isfinite(r[col]) else f"– (n={r[n]})"
        if p is not None:
            s += f", p={r[p]:.3f}{' *' if r['sig'] else ''}"
        return s
    e = e.assign(cell=e.apply(cell, axis=1))
    t = e.pivot_table(index=["condition", "pct_excluded"], columns="pair_class",
                      values="cell", aggfunc="first")[PAIR_CLASSES].reset_index()
    t["condition"] = pd.Categorical(t.condition, CONDS, ordered=True)
    t = t.sort_values(["condition", "pct_excluded"])
    t["pct_excluded"] = t.pct_excluded.astype(str) + " %"
    return t.rename(columns={"pct_excluded": "excluded"})


def heritability_rows(summ, set_type, cond="all", with_ctrl_enrichment=False):
    a = summ[(summ.condition == cond) & (summ.set_type == set_type)]
    rows = []
    for v in VKEYS:
        x = a[a.variant == v].set_index("group")
        r = {"excluded": pct(v),
             "fitted IMD/ctrl": f"{x.n_fitted['IMD']}/{x.n_fitted['non-IMD']}",
             "median log2E IMD": x.median_log2_enrichment["IMD"]}
        if with_ctrl_enrichment:
            r["median log2E ctrl"] = x.median_log2_enrichment["non-IMD"]
        r.update({"median τ* IMD": x.median_tau_star["IMD"],
                  "median τ* ctrl": x.median_tau_star["non-IMD"],
                  "τ* gap (IMD−ctrl)": x.median_tau_star["IMD"] - x.median_tau_star["non-IMD"],
                  "FDR sig enr IMD/ctrl": f"{x.n_sig_enrichment['IMD']}/{x.n_sig_enrichment['non-IMD']}",
                  "FDR sig τ* IMD/ctrl": f"{x.n_sig_tau_star['IMD']}/{x.n_sig_tau_star['non-IMD']}"})
        rows.append(r)
    return pd.DataFrame(rows)


def main():
    L = []
    hubs = read("hub_regulators.csv")
    frac = read("hub_anchor_fraction.csv")
    shifts = read("anchor_shifts.csv")
    exc = read("h1b_excess_summary.csv")
    deg = read("h1e_degree_null_summary.csv")
    rho = read("h1c_spearman.csv")
    size = read("h1d_set_size.csv")
    summ = read("h2b_summary.csv")
    delta = read("h2c_delta.csv")
    prec = read("h2d_precision.csv")
    sizes = read("set_sizes.csv")

    L += ["# Hub exclusion: numbers for the text", "",
          "Generated by `vis/hub_exclusion/07_numbers_for_text.py` from "
          "`figures/hub_exclusion/data/`. Variants: 0 % (deg0), 1 % (hub0.99), "
          "5 % (hub0.95), 10 % (hub0.90) of regulators excluded per condition. "
          "**Scope labels:** *[per condition]* = one value per condition (Rest, Stim8hr, "
          "Stim48hr); *[pooled]* = trait x condition sets pooled over the three conditions; "
          "*[Stim8hr]* = that condition only.", "",
          "## Setup and checks", "",
          "- **Joint fits.** All S-LDSC estimates come from joint per-condition fits "
          "(baselineLD + anchors + regulators + targets). Each τ* is conditional on the "
          "other two sets in its run, so a change in one set's τ* can reflect changes "
          "in the other sets of the same fit.",
          "- **Hub list.** Drop n_total_de_genes > cutoff within each condition. Integer "
          "cutoffs that reproduce every published gene set: " + "; ".join(
              f"{pct(v)}: " + ", ".join(f"{c} {k}" for c, k in HUB_CUTOFF[v].items())
              for v in VKEYS[1:]) + ". In Stim8hr at 10 %, UQCC1 (n = 153) is treated as "
          "a hub (152 and 153 both reproduce the sets). Rebuilding all 648 sets "
          "(4 variants x 162) from the hub-filtered graph gives 0 mismatches "
          "(`data/gene_set_rebuild.csv`).",
          "- **Expected Jaccard, two versions.** Size-only: the expectation of "
          "`04_jaccard_heatmaps.py` (random sets of the observed sizes from the variant's "
          "hub-filtered universe). Degree-aware (`01b_degree_null.py`): each regulator set "
          "redrawn with the same count per out-degree bin from the variant's hub-filtered "
          "universe (out-degree in that graph; 9–12 bins after merging), independently per "
          "trait, 1,000 draws; empirical one-sided p for the pair-class median, BH within "
          "each variant over the 9 class x condition tests.",
          "- **Targets** change only through anchor loss: a target set is the out-edges of "
          "the trait's anchor perturbations, so removing a non-anchor hub leaves it "
          "unchanged. They are reported in the last section and shown in supplementary "
          "figures only.", ""]

    fitted = shifts[shifts.status == "fitted"].assign(flip=lambda s: (
        (s.tau_star_sig != s.tau_star_sig_deg0) | (s.enrichment_sig != s.enrichment_sig_deg0)))
    a = fitted.groupby("variant").agg(
        n=("tau_star_shift_in_se", "count"),
        max_abs_tau_star_shift_se=("tau_star_shift_in_se", lambda x: x.abs().max()),
        max_abs_enrichment_shift_se=("enrichment_shift_in_se", lambda x: x.abs().max()),
        fdr_call_changes=("flip", "sum")).reindex(VKEYS[1:])
    L += ["### Anchor tolerance check (replaces identity check) [pooled]", "",
          "Anchor annotations are identical across variants (Prop._SNPs difference 0); "
          "their estimates move only through the joint fit. Shifts in units of the "
          "deg0 SE over all 45 fitted anchor trait x condition cells "
          "(`data/anchor_shifts.csv`):", "",
          md(a.reset_index().assign(variant=lambda d: d.variant.map(pct))), ""]

    # Hub anchors
    L += ["## Hub anchors dropped [per condition]", ""]
    ha = hubs[hubs.is_anchor]
    for v in VKEYS[1:]:
        L += [f"**{pct(v)} excluded**", ""]
        for c in CONDS:
            g = ha[(ha.pct_excluded == PCT[v]) & (ha.condition == c)]
            L.append(f"- {c}: " + ("none" if g.empty else "; ".join(
                f"{r.gene} ({r.n_degs} DEGs; {r.anchor_traits})" for r in g.itertuples())))
        L.append("")
    L += ["Hubs among perturbed anchors vs all perturbations (k hubs / n perturbations "
          "with ≥ 1 edge in deg0; a gene x condition counts once per condition; "
          "descriptive, no test):", ""]
    f = frac.copy()
    f["condition"] = pd.Categorical(f.condition, CONDS + ["all"], ordered=True)
    f = f.sort_values(["pct_excluded", "condition"])
    L += [md(pd.DataFrame({
        "excluded": f.variant.map(pct),
        "scope": ["[pooled]" if c == "all" else f"[{c}]" for c in f.condition],
        "IMD anchors": [kn(k, n) for k, n in zip(f.hubs_IMD_anchors, f.n_IMD_anchors)],
        "control anchors": [kn(k, n) for k, n in zip(f.hubs_control_anchors, f.n_control_anchors)],
        "all perturbations": [kn(k, n) for k, n in zip(f.hubs_all, f.n_all)]})), ""]

    # Q1
    reg = exc[(exc.set_type == "Regulators") & exc.pair_class.isin(PAIR_CLASSES)]
    dg = deg[deg.pair_class.isin(PAIR_CLASSES)].rename(
        columns={"median_excess_degree": "median"})
    L += ["## Q1: regulator-set overlap (fig_h1)", "",
          "Median excess Jaccard (observed − expected) by pair class [per condition]; "
          "related-GWAS pairs excluded; n = pairs with a defined expectation.", "",
          "**Size-only expectation (fig_h1 B)**", "", md(class_table(reg)), "",
          "**Degree-aware expectation (fig_h1 E)**; p = empirical one-sided "
          "(minimum 1/1,001), * = BH FDR < 0.05 within the variant", "",
          md(class_table(dg, p="p_empirical")), ""]
    r = rho[rho.set_type == "Regulators"].pivot_table(
        index="condition", columns="pct_excluded", values="spearman_rho").reindex(CONDS).reset_index()
    r.columns = [f"{c} %" if isinstance(c, (int, np.integer)) else c for c in r.columns]
    L += ["Spearman ρ of pairwise size-only excess vs 0 % (fig_h1 C) [per condition]; "
          "136 pairs (all with both sets non-empty at that threshold):", "", md(r), ""]
    s = size.pivot_table(index="condition", columns="pct_excluded",
                         values="median_pct_of_universe").reindex(CONDS).reset_index()
    s.columns = [f"{c} %" if isinstance(c, (int, np.integer)) else c for c in s.columns]
    L += ["Median regulator-set size, % of the variant's regulator universe "
          "(fig_h1 D) [per condition, median over 18 traits]:", "", md(s, "{:.2f}"), ""]

    # Q2
    L += ["## Q2: regulator-set heritability (fig_h2)", "",
          "Medians over fitted sets; FDR = BH < 0.05 within each variant (regulators + "
          "targets family, as Fig. 4; τ* one-sided). Control median log2 enrichment is "
          "not summarised here (different traits fitted per variant, noisy estimates; "
          "values in `data/h2b_summary.csv` and fig_h2 B).", "",
          "**[pooled] (36 IMD / 18 control trait x condition sets)**", "",
          md(heritability_rows(summ, "Regulators")), ""]
    for c in CONDS:
        L += [f"**[{c}]**", "", md(heritability_rows(summ, "Regulators", c)), ""]

    p = prec[(prec.annot == "regulators_H4") & (prec.status == "fitted") & (prec.group == "IMD")]
    pt = p.groupby("pct_excluded").agg(
        n=("study", "size"),
        median_prop_snps_pct=("prop_snps", lambda x: 100 * x.median()),
        median_enrichment_se=("enrichment_se", "median"),
        median_ci_width_enrichment=("ci_width_enrichment", "median"),
        median_ci_width_log2_enrichment=("ci_width_log2_enrichment", "median")).reset_index()
    pt["pct_excluded"] = pt.pct_excluded.astype(str) + " %"
    L += ["Precision of IMD regulator sets (fig_h2 D) [pooled over conditions]: median "
          "% of SNPs in the annotation, enrichment SE, and 95 % CI width of enrichment "
          "(2 x 1.96 x SE) and of log2 enrichment (delta method):", "",
          md(pt.rename(columns={"pct_excluded": "excluded"}), "{:.3f}"), ""]

    test = (f"Test: z = Δ / sqrt(se₁² + se₂²), two-sided, BH within each variant over all "
            f"regulator + target sets, all conditions ({CONSERVATIVE}). Regulator Δτ* also "
            f"reflects the target annotation changing within the same joint fit.")
    L += ["### Sets whose estimates change vs 0 % [per set; tests pooled over conditions "
          "for the FDR]", "", test, ""]
    for col, lab in [("delta_tau_star", "Δτ*"), ("delta_log2_enrichment", "Δ log2 enrichment")]:
        for annot, name in [("regulators_H4", "Regulator sets"), ("targets_H4", "Target sets")]:
            d = delta[delta.annot == annot]
            sig = d[d[f"{col}_sig"] == True]  # noqa: E712
            nom = d[d[f"{col}_p"] < 0.05].groupby("pct_excluded").size()
            L.append(f"- {name}, {lab}, FDR < 0.05: " + ("none" if sig.empty else "; ".join(
                f"{r.disease} {r.condition} at {r.pct_excluded} % (Δ = {r[col]:+.3f}"
                f"{', lost anchor' if r.lost_anchor else ''})" for _, r in sig.iterrows()))
                + ". Nominal p < 0.05 (uncorrected): " + ("none" if nom.empty else ", ".join(
                    f"{k} at {q} %" for q, k in nom.items()))
                + f" of {int(d[f'{col}_p'].notna().sum())} tests.")
    L.append("")

    # Targets (supplementary)
    L += ["## Targets (supplementary figures only)", "",
          "Target sets change only through anchor loss. Fixed subset with no seeding "
          "anchor lost even at 10 % (and so at every threshold; hub lists are nested): "
          + ", ".join(f"{g} {n}" for g, n in sizes[
              (sizes.variant == "deg0") & (sizes.annot == "targets_H4") & sizes.unchanged_10]
              .groupby("group").size().items())
          + " trait x condition sets (of 36 IMD, 18 control). These sets are identical "
          "across variants; their estimates move only through the joint fit "
          "(e.g. the regulator annotation in the same run shrinking).", ""]
    lost = sizes[sizes.lost_anchor].groupby(["pct_excluded", "group"]).size().unstack(fill_value=0)
    L += ["Target sets that lost ≥ 1 seeding anchor [pooled; of 36 IMD / 18 control]: "
          + "; ".join(f"{q} %: IMD {r.get('IMD', 0)}/36, control {r.get('non-IMD', 0)}/18"
                      for q, r in lost.iterrows()) + ".", ""]
    for st in ["Targets, all sets", "Targets, anchors unchanged"]:
        e = exc[(exc.set_type == st) & exc.pair_class.isin(PAIR_CLASSES)]
        L += [f"**{st}: median size-only excess Jaccard [per condition]**", "",
              md(class_table(e)), ""]
    r = rho[rho.set_type != "Regulators"]
    rt = r.pivot_table(index=["set_type", "condition"], columns="pct_excluded",
                       values="spearman_rho").reset_index()
    nn = r[r.pct_excluded == 10].set_index(["set_type", "condition"]).n_pairs
    rt["n pairs (10 %)"] = [nn[(a_, b_)] for a_, b_ in zip(rt.set_type, rt.condition)]
    rt.columns = [f"{c} %" if isinstance(c, (int, np.integer)) else c for c in rt.columns]
    L += ["Spearman ρ of target-set excess vs 0 % [per condition]:", "", md(rt), ""]
    for st in ["Targets, all sets", "Targets, anchors unchanged"]:
        L += [f"**{st}: heritability [pooled]**", "",
              md(heritability_rows(summ, st, with_ctrl_enrichment=False)), ""]

    # Closing statement
    at = lambda t, q: t[t.pct_excluded == q].set_index(["condition", "pair_class"])  # noqa: E731
    reg0, reg10 = at(reg, 0)["median"], at(reg, 10)["median"]
    degc = deg[deg.pair_class.isin(PAIR_CLASSES)]      # related pairs not summarised
    dg0, dg10 = at(degc, 0), at(degc, 10)
    fell = (reg10 < reg0).all()
    imd_deg = dg10.xs("IMD–IMD", level="pair_class")
    other_deg = dg10.drop(index="IMD–IMD", level="pair_class")
    q = heritability_rows(summ, "Regulators").set_index("excluded")
    s0 = summ[(summ.condition == "all") & (summ.set_type == "Regulators")
              & (summ.variant == "deg0")].set_index("group")
    L += ["## Did the predictions hold?", "",
          f"- **Q1 [per condition, regulator sets].** Against the size-only expectation, "
          f"median excess fell from 0 % to 10 % in every pair class and condition: "
          f"{'yes' if fell else 'no'} (IMD–IMD "
          + ", ".join(f"{c} {reg0[(c, 'IMD–IMD')]:.3f} → {reg10[(c, 'IMD–IMD')]:.3f}" for c in CONDS)
          + "). Against the degree-aware expectation, IMD–IMD median excess was "
          + ", ".join(f"{c} {dg0.loc[(c, 'IMD–IMD'), 'median_excess_degree']:.3f} → "
                      f"{imd_deg.loc[c, 'median_excess_degree']:.3f}" for c in CONDS)
          + f" (0 % → 10 %), with FDR < 0.05 at 10 % in "
          f"{int(imd_deg.sig.sum())}/3 conditions; IMD–control and control–control at 10 % "
          f"had FDR < 0.05 in {int(other_deg.sig.sum())}/6 class x condition tests "
          f"(medians {other_deg.median_excess_degree.min():+.3f} to "
          f"{other_deg.median_excess_degree.max():+.3f}). Spearman ρ of size-only excess "
          f"vs 0 % at 10 %: "
          + ", ".join(f"{c} {v:.2f}" for c, v in rho[(rho.set_type == 'Regulators')
                                                      & (rho.pct_excluded == 10)]
                      .set_index("condition").spearman_rho.reindex(CONDS).items()) + ".",
          f"- **Q2 [pooled, regulator sets].** At 0 % the control regulator sets carried "
          f"almost no signal: {s0.n_sig_enrichment['non-IMD']}/{s0.n_fitted['non-IMD']} "
          f"fitted control sets FDR-significant for enrichment, "
          f"{s0.n_sig_tau_star['non-IMD']} for τ*, median τ* "
          f"{s0.median_tau_star['non-IMD']:+.3f}. The prediction that control-trait signal "
          f"falls more than IMD signal therefore could not be tested. IMD regulator sets: "
          f"median τ* {q.loc['0 %', 'median τ* IMD']:.3f} → {q.loc['10 %', 'median τ* IMD']:.3f}; "
          f"FDR-significant for enrichment {q.loc['0 %', 'FDR sig enr IMD/ctrl'].split('/')[0]}/36 "
          f"→ {q.loc['10 %', 'FDR sig enr IMD/ctrl'].split('/')[0]}/36; median 95 % CI width "
          f"of enrichment {pt.median_ci_width_enrichment.iloc[0]:.2f} → "
          f"{pt.median_ci_width_enrichment.iloc[-1]:.2f}. No regulator set's τ* changed at "
          f"FDR < 0.05 under the conservative test.",
          ""]
    (OUT / "numbers_for_text.md").write_text("\n".join(L))
    print(f"Wrote {OUT / 'numbers_for_text.md'}")


if __name__ == "__main__":
    main()
